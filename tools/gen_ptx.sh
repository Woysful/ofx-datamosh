#!/bin/sh
# Regenerates src/mosh_kernels.ptx from src/mosh_kernels.cl with NVRTC.
# Needs the NVRTC headers and library of CUDA 11 or newer (a CUDA toolkit,
# or the nvidia-cuda-nvrtc-cu11 pip package); ptxas, when found, checks the
# result.
#   NVRTC_INC=/usr/local/cuda/include NVRTC_LIB=/usr/local/cuda/lib64 tools/gen_ptx.sh
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
NVRTC_INC=${NVRTC_INC:-/usr/local/cuda/include}
NVRTC_LIB=${NVRTC_LIB:-/usr/local/cuda/lib64}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
c++ -O1 "$ROOT/tools/gen_ptx.cpp" -I"$NVRTC_INC" -L"$NVRTC_LIB" -lnvrtc -Wl,-rpath,"$NVRTC_LIB" -o "$tmp/gen_ptx"
"$tmp/gen_ptx" "$ROOT/src/mosh_kernels.cl" "$tmp/k.ptx"
# Every instruction the kernels use exists in PTX ISA 6.0, so drivers back
# to CUDA 9 can load the file; ptxas rejects it if that stops being true.
sed 's/^\.version .*/.version 6.0/' "$tmp/k.ptx" > "$tmp/k6.ptx"
PTXAS=${PTXAS:-$(command -v ptxas || true)}
if [ -n "$PTXAS" ]; then
  for arch in sm_50 sm_75 sm_86 sm_90; do "$PTXAS" -arch=$arch "$tmp/k6.ptx" -o "$tmp/k.cubin"; done
  echo "ptxas: ok"
fi
if command -v sha256sum >/dev/null; then hash=$(sha256sum "$ROOT/src/mosh_kernels.cl" | cut -d' ' -f1)
else hash=$(shasum -a 256 "$ROOT/src/mosh_kernels.cl" | cut -d' ' -f1); fi
{
  echo "// mosh_kernels.cl sha256 $hash"
  echo "// Generated by tools/gen_ptx.sh from src/mosh_kernels.cl; do not edit."
  cat "$tmp/k6.ptx"
} > "$ROOT/src/mosh_kernels.ptx"
echo "wrote src/mosh_kernels.ptx"
